// The renderer's one defence against hostile markup is the allowlist sanitizer in
// workbench/markdown.ts. Agent output, repo files and web pages all end up as HTML on the board, and
// the preload bridge reaches the whole main process, so a single unsanitized innerHTML is worth a
// lot more than a defaced panel.
//
// Two panels once called marked.parse() directly and rendered the result raw. The e2e sanitize test
// did not catch it, because it exercised the function those panels *should* have called. These are
// the structural rules that keep that from coming back.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SRC = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'src')

function walk(dir: string, out: string[] = []): string[] {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (/\.tsx?$/.test(e.name)) out.push(p)
  }
  return out
}
const FILES = walk(SRC).map((p) => ({ rel: path.relative(SRC, p).split(path.sep).join('/'), text: fs.readFileSync(p, 'utf8') }))

/**
 * `marked` turns markdown into HTML and has had no sanitizer of its own since v5, so its output is
 * only safe once it has been through sanitizeHtml. This is the one module that does that, and the
 * only one allowed to import it.
 */
// One module parses markdown now. studios/docs/render.ts used to call marked.parse itself, which is
// why a document there got no relative images and no highlighting; it goes through renderMarkdown.
const MAY_IMPORT_MARKED = ['renderer/src/workbench/markdown.ts']

test('only the sanitizing modules import marked', () => {
  const importers = FILES.filter((f) => /from 'marked'/.test(f.text)).map((f) => f.rel).sort()
  assert.deepEqual(importers, [...MAY_IMPORT_MARKED].sort(),
    'a new importer of marked must sanitize its output: render it with renderMarkdown instead')
})

test('each module that renders marked output sanitizes it', () => {
  for (const rel of MAY_IMPORT_MARKED) {
    const f = FILES.find((x) => x.rel === rel)!
    assert.match(f.text, /sanitizeHtml/, `${rel} must pass marked's output through sanitizeHtml`)
  }
})

/**
 * Anything writing raw HTML has to get that string from a sanitizer: renderMarkdown / sanitizeHtml,
 * highlightCode (which escapes), or the app's own QR generator. A file listed here without one of
 * those names is rendering something it did not sanitize.
 */
/**
 * The one file that renders raw HTML without naming a sanitizer, and why it is allowed to.
 * SettingsPanel draws the phone-Inbox QR code, which main builds with qrSvg() in shared/qr.ts: that
 * SVG interpolates only numbers and a path made of digits, and no part of the encoded URL is ever
 * placed in the markup, so there is nothing in it to sanitize.
 */
const RAW_HTML_EXCEPTIONS: Record<string, { reason: string; payload: RegExp }> = {
  'renderer/src/panels/SettingsPanel.tsx': { reason: 'the phone QR, generated by shared/qr.ts', payload: /__html: st\.qr \?\? ''/ }
}

test('every raw-HTML site sits in a file that also names a sanitizer', () => {
  const RAW = /dangerouslySetInnerHTML|\.innerHTML\s*=|insertAdjacentHTML|\.outerHTML\s*=/
  const SANITIZER = /renderMarkdown|sanitizeHtml|highlightCode|markdownToHtmlDocument/
  const offenders = FILES.filter(
    (f) => f.rel.startsWith('renderer/') && RAW.test(f.text) && !SANITIZER.test(f.text) && !RAW_HTML_EXCEPTIONS[f.rel]
  ).map((f) => f.rel)
  assert.deepEqual(offenders, [], 'these write raw HTML with no sanitizer in sight')
})

test('each documented exception still renders only what it was excused for', () => {
  for (const [rel, { reason, payload }] of Object.entries(RAW_HTML_EXCEPTIONS)) {
    const f = FILES.find((x) => x.rel === rel)
    assert.ok(f, `${rel} exists`)
    const sites = f.text.match(/__html:[^}]*/g) ?? []
    assert.equal(sites.length, 1, `${rel} is excused for one thing only (${reason})`)
    assert.match(sites[0], payload, `${rel} renders something other than ${reason}`)
  }
  // and the generator really is the app's own, with no caller text in the markup
  const qr = FILES.find((x) => x.rel === '../shared/qr.ts' || x.rel === 'shared/qr.ts')!
  assert.doesNotMatch(qr.text, /\$\{text\}/, 'qrSvg must never interpolate the encoded text into the SVG')
})

test('the two panels that stream an agent brief use the sanitizing renderer', () => {
  for (const rel of ['renderer/src/panels/HandoffPanel.tsx', 'renderer/src/panels/SweepPanel.tsx']) {
    const f = FILES.find((x) => x.rel === rel)
    assert.ok(f, `${rel} exists`)
    assert.match(f.text, /renderMarkdown\(/, `${rel} must render its brief with renderMarkdown`)
    assert.doesNotMatch(f.text, /marked\.parse/, `${rel} must not parse markdown itself`)
  }
})

test('a secret is never generated with Math.random', () => {
  // the local servers' tokens come from crypto.randomBytes; Math.random is fine for React keys
  const offenders = FILES.filter(
    (f) => f.rel.startsWith('main/') && /Math\.random/.test(f.text) && /secret|token|Secret|Token/.test(f.text)
  ).map((f) => f.rel)
  assert.deepEqual(offenders, [], 'a secret or token must come from node:crypto, not Math.random')
})

test('a URL that comes out of the board file is checked before it is used', () => {
  // ~/.fleetboard/projects/<id>.json is written by the app and by agents, and these two read a URL
  // straight out of it into the DOM on every load
  const img = FILES.find((f) => f.rel === 'renderer/src/nodes/ImageNode.tsx')!
  assert.match(img.text, /safeUrl\(/, 'ImageNode must check node.data.src before it reaches <img src>')
})
